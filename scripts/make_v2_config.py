"""Write configs/v2.yaml = your configs/default.yaml (unchanged) + the v2 overrides below.

v1 keeps using configs/default.yaml and its outputs are never touched; every v2 command takes
--config configs/v2.yaml. Run once from the repo root:  python -m scripts.make_v2_config
"""

from __future__ import annotations

import copy
from pathlib import Path
from typing import Any

import yaml

V2_OVERRIDES: dict[str, Any] = {
    "data": {
        "processed_dir": "data/processed_v2",       # train/val npz + Stockfish labels (scripts.label_sf)
        "benchmark_dir": "data/benchmark_v2",       # fresh positions / openings (scripts.build_fresh_sets)
    },
    "label": {"mode": "blend", "blend_lambda": 0.5, "sf_nodes": 10000},
    "model": {"head_act": "leaky", "checkpoint": "src/model/checkpoints/best_model_v2.pt"},
    "train": {"weight_decay": 1.0e-4},
    "tournament": {"n_openings": 50, "anchors": {"elos": [1320]}},
    "v2": {
        "v1_checkpoint": "src/model/checkpoints/best_model.pt",  # for the v2_full_oldnet ablation
        "tablebase_dir": "data/syzygy",                          # 3-4-5 piece Syzygy WDL/DTZ files (optional)
        "safety": {"candidates": 6, "full_plies": 2, "margin_cp": 150, "max_nodes": 6000},
        "gate": "critical",                                      # critical | always | never | confidence
        "sims_critical": 400,                                    # sharp positions (in check / hanging / capture)
        "sims_normal": 200,                                      # other critical positions (endgame, few moves)
        "prior_temperature": 0.1,                               # None = mcts.prior_temperature (v1-tuned); dev choice §3
        "interior_prior_temperature": 1.0,
        "quiescence_leaf": True,
        "qleaf_scale": 0.25,                                     # value shift per pawn of resolved material
        "contempt": 0.10,                                        # draw value for the side that is better
        "contempt_min_winchance": 0.55,
        "endgame_npm": 13,                                       # non-pawn material per side (pawns) <= this
        "few_legal_moves": 12,
    },
}


def merge(base: dict[str, Any], over: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(base)
    for k, v in over.items():
        out[k] = merge(out.get(k, {}) or {}, v) if isinstance(v, dict) else v
    return out


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    base = yaml.safe_load((root / "configs" / "default.yaml").read_text())
    cfg = merge(base, V2_OVERRIDES)
    out = root / "configs" / "v2.yaml"
    out.write_text("# GENERATED by scripts/make_v2_config.py from configs/default.yaml + V2_OVERRIDES. Do not edit by hand.\n"
                   + yaml.safe_dump(cfg, sort_keys=False))
    print(f"wrote {out}")
    for k in ("data", "label", "model", "train"):
        print(f"  {k}: " + ", ".join(f"{a}={cfg[k][a]}" for a in V2_OVERRIDES[k]))


if __name__ == "__main__":
    main()
